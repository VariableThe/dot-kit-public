#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const dir=new URL('.',import.meta.url);
const files=['completion-core.mjs','completion-monitor.mjs','active-monitor.mjs','exec-bridge.mjs'];
let source='/* Generated by build-runtime.mjs. Do not edit. Existing tool callbacks only. */\n(() => {\n';
for (const file of files) {
  let body=await readFile(new URL(file,dir),'utf8');
  body=body.replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
  if (/^import |^export |\bprocess\.|\bimport\.meta/m.test(body)) throw Error(`Non-isolate code in ${file}`);
  source+=`\n// ${file}\n${body}\n`;
}
source+='return { runAndMonitor, monitorCompletion, classifyCompletion, payload, createToolBridge };\n})()\n';
const path=new URL('active-runtime.js',dir);
if (process.argv.includes('--check')) {
  if (await readFile(path,'utf8')!==source) throw Error('active-runtime.js is stale');
} else await writeFile(path,source);
console.log(`${process.argv.includes('--check')?'Verified':'Built'} ${fileURLToPath(path)}`);
